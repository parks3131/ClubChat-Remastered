/**
 * `MEDIA_URL_MODE=presign`, which had no test at all until this file.
 *
 * It is the mode the first production deploy ships, and it is the rollback lever if `cdn` mode
 * misbehaves after the Worker is cut over. A rollback lever nobody has pulled is not a lever, so
 * the two modes are proved to be genuinely exclusive here: in `presign` the URL is the object
 * store's and our HMAC is never applied, in `cdn` the store is never asked to presign anything,
 * and neither mode moves the authorization decision that sits in front of both.
 *
 * **Every value that can come from `media-signing-vectors.json` comes from there.** The vectors
 * are literal expected values generated by `openssl`, sharing no code with the module, and they
 * exist because the media suite once passed 52 tests with the signed separator mutated: an
 * assertion that signs and verifies through one implementation passes on self-consistent
 * nonsense. So the hour boundary this file crosses, the expiry the presign window ends at, and
 * the bucket each kind routes to are all read out of that file rather than recomputed by the
 * code under test.
 */

