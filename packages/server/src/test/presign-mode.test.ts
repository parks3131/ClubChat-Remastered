let h: TestDb;
let store: RecordingMediaStore;

/**
 * The vectors' own secret and base URL.
 *
 * That is what lets a `cdn`-mode URL in this file be compared against the literal string in the
 * vector set instead of against a second call to our own HMAC.
 */
const base: MediaConfig = {
  publicBucket: 'clubchat-identity',
  privateBucket: 'clubchat-content',
  signingSecret: vectors.secret,
  cdnBaseUrl: vectors.cdnBaseUrl,
};

const presignMode: MediaConfig = { ...base, urlMode: 'presign' };
const cdnMode: MediaConfig = { ...base, urlMode: 'cdn' };

/** Which bucket a role names here, so the mapping is read off the vector rather than assumed. */
function bucketForRole(role: string): string {
  if (role === 'identity') return base.publicBucket;
  if (role === 'content') return base.privateBucket;
  throw new Error(`the vector set names a bucket role this test does not know: ${role}`);
}

beforeAll(async () => {
  h = await startTestDb();
});

afterAll(async () => {
  await h?.stop();
});

beforeEach(async () => {
  await h.db.execute(sql`TRUNCATE notifications, outbox, media_objects RESTART IDENTITY CASCADE`);
  store = new RecordingMediaStore();
});

const ctxFor = (id: string) => loadAccessContext(h.db, id);

async function makeUser(name: string): Promise<string> {
  const id = crypto.randomUUID();
  await h.db.insert(users).values({ id, name, email: `${name}-${id.slice(0, 8)}@t.invalid` });
  return id;
}

/** A club with an Eboard the owner is alone in, a plain member, and somebody outside entirely. */
async function setup() {
  const ownerId = await makeUser('Owner');
  const memberId = await makeUser('Member');
  const outsiderId = await makeUser('Outsider');
  const club = await createClub(h.db, { name: 'Hillside', creatorId: ownerId });
  await addMember(h.db, await ctxFor(ownerId), club.clubId, memberId);
  return { ...club, ownerId, memberId, outsiderId };
}

/** A real, decodable image. `completeUpload` decodes what it accepts, so zeroes will not do. */
let encodedImage: Buffer | null = null;
async function jpegBytes(): Promise<Buffer> {
  if (encodedImage) return encodedImage;
  const sharp = (await import('sharp')).default;
  encodedImage = await sharp({
    create: { width: 64, height: 64, channels: 3, background: '#3355aa' },
  })
    .jpeg()
    .toBuffer();
  return encodedImage;
}

/** Intent, the client's direct PUT, then complete. The whole flow, as the routes run it. */
async function upload(
  userId: string,
  input: { kind: 'photo' | 'avatar'; channelId?: string | undefined },
): Promise<string> {
  const mime = 'image/jpeg';
  const image = await jpegBytes();
  const intent = await createUploadIntent(h.db, store, presignMode, await ctxFor(userId), {
    kind: input.kind,
    mime,
    bytes: image.byteLength,
    channelId: input.channelId,
  });
  expect(intent.ok, 'the upload intent was refused').toBe(true);
  if (!intent.ok) throw new Error('upload intent refused');

  const rows = await h.db
    .select()
    .from(mediaObjects)
    .where(eq(mediaObjects.id, intent.mediaId))
    .limit(1);
  const row = rows[0];
  if (!row) throw new Error('the intent wrote no media row');
  store.simulateUpload(row.bucket, row.objectKey, new Uint8Array(image), mime);

  const completed = await completeUpload(h.db, store, await ctxFor(userId), intent.mediaId);
  expect(completed.ok, 'completing the upload failed').toBe(true);
  return intent.mediaId;
}

/**
 * Force a row's object key to a vector's.
 *
 * The real key is `${kind}/${YYYY-MM}/${uuid}` and random by construction, which is exactly what
 * it should be and exactly what makes a literal expected URL impossible. Pinning it is what lets
 * an assertion here name the vector's URL rather than call our own signer a second time.
 */
async function pinObjectKey(
  mediaId: string,
  objectKey: string,
  variants: Record<string, string> = {},
): Promise<void> {
  await h.db.update(mediaObjects).set({ objectKey, variants }).where(eq(mediaObjects.id, mediaId));
}

// ===========================================================================
// The two modes are exclusive
// ===========================================================================

describe('presign mode hands back the store URL and not our own signature', () => {
  it('resolves to exactly the string the store returned, carrying no exp or sig of ours', async () => {
    const f = await setup();
    const mediaId = await upload(f.ownerId, { kind: 'photo', channelId: f.mainChannelId });
    await pinObjectKey(mediaId, PHOTO.objectKey);

    const result = await resolveMediaRedirect(
      h.db,
      store,
      presignMode,
      await ctxFor(f.ownerId),
      mediaId,
      { nowMs: IN_WINDOW_MS },
    );
    expect(result.ok).toBe(true);
    if (!result.ok) return;

    // The store was asked, once, and its answer is what the caller got. Not a URL that merely
    // looks like it: the identical string.
    const call = store.onlyPresign();
    expect(result.url).toBe(call.url);
    expect(call.objectKey).toBe(PHOTO.objectKey);

    // Nothing of the CDN scheme is on it. `exp` and `sig` are the pair the Worker validates,
    // and an object store has never heard of either.
    const query = new URL(result.url).searchParams;
    expect(query.get('exp'), 'a presign-mode URL carried our own expiry').toBeNull();
    expect(query.get('sig'), 'a presign-mode URL carried our own signature').toBeNull();
    expect(result.url.startsWith(base.cdnBaseUrl)).toBe(false);

    // And the CDN URL for this same object at this same instant is a different string, which is
    // what makes every assertion above about the MODE rather than about the fixture.
    expect(result.url).not.toBe(PHOTO.url);

    // Unchanged by the mode: this is still one member's authorization decision, so a shared
    // cache holding it would serve that decision to somebody else.
    expect(result.cacheControl).toBe('private, max-age=600');
  });

  it('never asks the store to presign in cdn mode, and mints the vector URL instead', async () => {
    const f = await setup();
    const mediaId = await upload(f.ownerId, { kind: 'photo', channelId: f.mainChannelId });
    await pinObjectKey(mediaId, PHOTO.objectKey);

    const result = await resolveMediaRedirect(
      h.db,
      store,
      cdnMode,
      await ctxFor(f.ownerId),
      mediaId,
      { nowMs: IN_WINDOW_MS },
    );
    expect(result.ok).toBe(true);
    if (!result.ok) return;

    // The literal string from the vector set, generated by openssl and sharing no code with the
    // signer. Both the expiry and the signature are pinned by it.
    expect(result.url).toBe(PHOTO.url);
    expect(
      store.presignDownloads,
      'cdn mode asked the object store to presign a download',
    ).toEqual([]);
  });

  it('does not presign when MEDIA_URL_MODE is absent, because the default is cdn', async () => {
    // config.ts: "Defaults to `cdn` so a missing value in production cannot silently start
    // handing out store-signed URLs." A store-signed URL is a direct bucket URL, so a config
    // that lost this key must fail closed towards the edge rather than open towards R2.
    const f = await setup();
    const mediaId = await upload(f.ownerId, { kind: 'photo', channelId: f.mainChannelId });
    await pinObjectKey(mediaId, PHOTO.objectKey);

    const result = await resolveMediaRedirect(
      h.db,
      store,
      base,
      await ctxFor(f.ownerId),
      mediaId,
      { nowMs: IN_WINDOW_MS },
    );
    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(result.url).toBe(PHOTO.url);
    expect(store.presignDownloads).toEqual([]);
  });
});

// ===========================================================================
// The window: hour aligned, and dated from the floor
// ===========================================================================

describe('the presign window', () => {
  async function presignedPhotoUrl(f: { ownerId: string }, mediaId: string, nowMs: number) {
    const result = await resolveMediaRedirect(
      h.db,
      store,
      presignMode,
      await ctxFor(f.ownerId),
      mediaId,
      { nowMs },
    );
    expect(result.ok).toBe(true);
    if (!result.ok) throw new Error('the photo did not resolve');
    return result.url;
  }

  it('is byte identical for every viewer inside the hour', async () => {
    // THE point of the alignment, and the whole reason `presignDownload` takes a date at all. A
    // URL signed at "now" changes every request, the query string is part of every cache key, so
    // 300 members of a club become 300 origin fetches.
    const f = await setup();
    const mediaId = await upload(f.ownerId, { kind: 'photo', channelId: f.mainChannelId });
    await pinObjectKey(mediaId, PHOTO.objectKey);

    const first = await presignedPhotoUrl(f, mediaId, WINDOW_FLOOR_MS + 1);
    const minutesLater = await presignedPhotoUrl(f, mediaId, IN_WINDOW_MS);
    const lastMillisecond = await presignedPhotoUrl(f, mediaId, BOUNDARY_MS - 1);

    expect(minutesLater).toBe(first);
    expect(lastMillisecond).toBe(first);

    expect(store.presignDownloads).toHaveLength(3);
    for (const call of store.presignDownloads) {
      expect(call.signingDateMs).toBe(WINDOW_FLOOR_MS);
      expect(call.expiresInSeconds).toBe((2 * HOUR_MS) / 1000);
    }
  });

  it('dates the signature at the FLOOR of the hour, never at the expiry', async () => {
    const f = await setup();
    const mediaId = await upload(f.ownerId, { kind: 'photo', channelId: f.mainChannelId });
    await pinObjectKey(mediaId, PHOTO.objectKey);
    await presignedPhotoUrl(f, mediaId, IN_WINDOW_MS);

    const call = store.onlyPresign();
    // Pinned four ways. It sits on an hour boundary, it is in the past, it is not the expiry,
    // and the window it opens ENDS at the expiry the vector set names for this instant.
    expect(call.signingDateMs).toBe(WINDOW_FLOOR_MS);
    expect(call.signingDateMs % HOUR_MS).toBe(0);
    expect(
      call.signingDateMs,
      'the signature was dated in the future, where it is not yet valid',
    ).toBeLessThan(IN_WINDOW_MS);
    expect(call.signingDateMs).not.toBe(PHOTO.exp * 1000);
    expect(call.signingDateMs / 1000 + call.expiresInSeconds).toBe(PHOTO.exp);

    // Two hours, because the scheme is ceil-to-the-hour plus an hour of headroom: a URL issued
    // at 10:59 must not die sixty seconds later. Measured from the floor, that is 7200 seconds.
    expect(call.expiresInSeconds).toBe((2 * HOUR_MS) / 1000);
  });

  it('crosses to a new URL exactly at the hour boundary the vectors pin', async () => {
    const f = await setup();
    const mediaId = await upload(f.ownerId, { kind: 'photo', channelId: f.mainChannelId });
    await pinObjectKey(mediaId, PHOTO.objectKey);

    const before = await presignedPhotoUrl(f, mediaId, BOUNDARY_MS - 1);
    const atBoundary = await presignedPhotoUrl(f, mediaId, BOUNDARY_MS);
    const after = await presignedPhotoUrl(f, mediaId, BOUNDARY_MS + 1);

    expect(atBoundary, 'the URL survived the hour boundary unchanged').not.toBe(before);

    const calls = store.presignDownloads;
    expect(calls).toHaveLength(3);
    const [one, two, three] = calls;
    if (!one || !two || !three) throw new Error('the store was not asked three times');

    // The floor moves at the boundary and not before it.
    expect(one.signingDateMs).toBe(WINDOW_FLOOR_MS);
    expect(two.signingDateMs).toBe(BOUNDARY_MS);
    expect(three.signingDateMs).toBe(BOUNDARY_MS);

    // Every window still ends on an aligned expiry the vector set names, which is what ties this
    // boundary to the CDN mode's own boundary rather than to arithmetic repeated here.
    expect(one.signingDateMs / 1000 + one.expiresInSeconds).toBe(PHOTO.exp);
    expect(two.signingDateMs / 1000 + two.expiresInSeconds).toBe(PHOTO.exp);
    expect(three.signingDateMs / 1000 + three.expiresInSeconds).toBe(NEXT_HOUR.exp);

    /*
     * The exact boundary millisecond is a window of its own, and this records it rather than
     * hides it. `hourAlignedExpiry` is `ceil`, so it changes on the half-open interval
     * `(H, H + 1h]`, while the signing floor changes on `[H, H + 1h)`. The two are offset by one
     * millisecond, so a caller landing precisely on H is signed from H to H + 1h while everybody
     * for the rest of that hour is signed from H to H + 2h. Harmless - the URL is still valid for
     * a full hour and it is one millisecond in every 3,600,000 - but it is a real seam, and a
     * later change that closes it should have to come past this assertion on purpose.
     */
    expect(two.expiresInSeconds).toBe(HOUR_MS / 1000);
    expect(after).not.toBe(atBoundary);
  });
});

