describe('the bucket a kind is presigned against', () => {
  it('presigns an avatar against the public bucket and a photo against the private one', async () => {
    const f = await setup();
    const photoId = await upload(f.ownerId, { kind: 'photo', channelId: f.mainChannelId });
    const avatarId = await upload(f.ownerId, { kind: 'avatar' });
    await pinObjectKey(photoId, PHOTO.objectKey);
    await pinObjectKey(avatarId, AVATAR.objectKey);

    // Through the batch path, which is what a gallery and the client's `/media/urls` call use,
    // and where a per-object decision is easiest to lose to a single shared value.
    const resolved = await resolveMediaRedirects(
      h.db,
      store,
      presignMode,
      await ctxFor(f.memberId),
      [photoId, avatarId],
      { nowMs: IN_WINDOW_MS },
    );
    expect(resolved.size).toBe(2);
    expect(store.presignDownloads).toHaveLength(2);

    const byKey = new Map(store.presignDownloads.map((call) => [call.objectKey, call]));
    // The role comes off the vector, so the mapping being asserted is the one the Worker routes
    // by rather than one restated here.
    expect(byKey.get(PHOTO.objectKey)?.bucket).toBe(bucketForRole(PHOTO.bucketRole));
    expect(byKey.get(AVATAR.objectKey)?.bucket).toBe(bucketForRole(AVATAR.bucketRole));
    expect(
      byKey.get(PHOTO.objectKey)?.bucket,
      'both kinds were presigned against the same bucket',
    ).not.toBe(byKey.get(AVATAR.objectKey)?.bucket);

    expect(resolved.get(photoId)?.url).not.toBe(resolved.get(avatarId)?.url);
  });
});

