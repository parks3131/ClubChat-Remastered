describe('a derived variant in presign mode', () => {
  it('presigns the variant key rather than the original', async () => {
    const f = await setup();
    const mediaId = await upload(f.ownerId, { kind: 'photo', channelId: f.mainChannelId });
    await pinObjectKey(mediaId, PHOTO.objectKey, { thumb: THUMB.objectKey });

    const presigned = await resolveMediaRedirect(
      h.db,
      store,
      presignMode,
      await ctxFor(f.ownerId),
      mediaId,
      { variant: 'thumb', nowMs: IN_WINDOW_MS },
    );
    expect(presigned.ok).toBe(true);
    if (!presigned.ok) return;

    const call = store.onlyPresign();
    expect(call.objectKey, 'the original was presigned instead of the thumbnail').toBe(
      THUMB.objectKey,
    );
    // Read off the same branch the key was, so the two can never describe different bytes.
    expect(presigned.mime).toBe('image/webp');

    // The same variant in cdn mode is the vector's own URL for that key, and asks the store for
    // nothing. Two vectors, one object, one instant: the modes differ and nothing else does.
    const signed = await resolveMediaRedirect(
      h.db,
      store,
      cdnMode,
      await ctxFor(f.ownerId),
      mediaId,
      { variant: 'thumb', nowMs: IN_WINDOW_MS },
    );
    expect(signed.ok).toBe(true);
    if (!signed.ok) return;
    expect(signed.url).toBe(THUMB.url);
    expect(store.presignDownloads).toHaveLength(1);
  });
});
