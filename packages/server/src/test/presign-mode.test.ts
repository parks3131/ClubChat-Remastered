// ---------------------------------------------------------------------------
// A store that records what it was asked to sign
// ---------------------------------------------------------------------------

type PresignDownloadCall = {
  bucket: string;
  objectKey: string;
  signingDateMs: number;
  expiresInSeconds: number;
  /** What this call handed back, so a test can assert the resolved URL IS the store's answer. */
  url: string;
};

/**
 * `FakeMediaStore` plus a record of every `presignDownload`.
 *
 * The URL is shaped like a real S3 presigned GET rather than like anything this codebase mints,
 * so "the URL came from the store" is something an assertion can see rather than infer. Its
 * signature is a hash of the four inputs and nothing else, exactly as a real one is a signature
 * over them: byte-identical output therefore means byte-identical input, which is the property
 * the hour alignment exists to give and the one a per-call clock would destroy.
 */
class RecordingMediaStore extends FakeMediaStore {
  readonly presignDownloads: PresignDownloadCall[] = [];

  override async presignDownload(input: {
    bucket: string;
    objectKey: string;
    signingDateMs: number;
    expiresInSeconds: number;
  }): Promise<string> {
    const stamp = new Date(input.signingDateMs).toISOString().replace(/[-:]|\.\d{3}/g, '');
    const signature = createHash('sha256')
      .update(
        `${input.bucket}/${input.objectKey}:${input.signingDateMs}:${input.expiresInSeconds}`,
      )
      .digest('hex');
    const url =
      `https://object-store.invalid/${input.bucket}/${input.objectKey}` +
      `?X-Amz-Date=${stamp}&X-Amz-Expires=${input.expiresInSeconds}&X-Amz-Signature=${signature}`;
    this.presignDownloads.push({ ...input, url });
    return url;
  }

  /** The single call a test expected, or a failure that says how many there really were. */
  onlyPresign(): PresignDownloadCall {
    const [first] = this.presignDownloads;
    if (this.presignDownloads.length !== 1 || !first) {
      throw new Error(
        `expected exactly one presignDownload, saw ${this.presignDownloads.length}`,
      );
    }
    return first;
  }
}

// ---------------------------------------------------------------------------
// The vectors, and the timeline derived from them
// ---------------------------------------------------------------------------

function signVector(name: string) {
  const found = vectors.sign.find((v) => v.name === name);
  if (!found) throw new Error(`the vector set has no signing vector named "${name}"`);
  return found;
}

const PHOTO = signVector('a plain photo key, the ordinary case');
const THUMB = signVector('a derived variant, whose key carries two dots');
const AVATAR = signVector('an avatar, which lives in the other bucket');
/** The vector one hour after `PHOTO`, which is what makes the boundary below vector-derived. */
const NEXT_HOUR = signVector('a document, private like a photo');

/**
 * One hour in milliseconds, taken from the gap between two adjacent vectors.
 *
 * Deliberately not restated as `3_600_000`: a test that hardcodes the period the code under test
 * also hardcodes agrees with itself and proves nothing about either.
 */
const HOUR_MS = (NEXT_HOUR.exp - PHOTO.exp) * 1000;

/**
 * The floor of the hour a caller is standing in when the aligned expiry is `PHOTO.exp`.
 *
 * The scheme is `ceil(now, 1h) + 1h`, so an instant strictly inside an hour expires two hours
 * after that hour's floor. This is the value the presigned URL must be DATED with.
 */
const WINDOW_FLOOR_MS = PHOTO.exp * 1000 - 2 * HOUR_MS;

/** The next hour boundary: the last instant whose aligned expiry is still `PHOTO.exp`. */
const BOUNDARY_MS = PHOTO.exp * 1000 - HOUR_MS;

/** An ordinary instant inside that hour, about twenty minutes in. */
const IN_WINDOW_MS = WINDOW_FLOOR_MS + 1_237_811;

