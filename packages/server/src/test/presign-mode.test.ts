describe('authorization is unchanged by the URL mode', () => {
  it('refuses an Eboard photo to everyone outside the space, in BOTH modes', async () => {
    const f = await setup();
    // The owner is the only Eboard member, from club creation.
    const mediaId = await upload(f.ownerId, { kind: 'photo', channelId: f.eboardChannelId });

    // The positive control first, so the refusals below cannot pass by the object being broken.
    const allowed = await resolveMediaRedirect(
      h.db,
      store,
      presignMode,
      await ctxFor(f.ownerId),
      mediaId,
      { nowMs: IN_WINDOW_MS },
    );
    expect(allowed.ok, 'the Eboard member could not reach their own photo').toBe(true);
    expect(store.presignDownloads).toHaveLength(1);

    const strangers = [
      { who: 'a plain club member, who is not in the Eboard space', id: f.memberId },
      { who: 'a complete outsider', id: f.outsiderId },
    ];
    const modes = [
      { name: 'presign', config: presignMode },
      { name: 'cdn', config: cdnMode },
    ];

    for (const stranger of strangers) {
      for (const mode of modes) {
        const refused = await resolveMediaRedirect(
          h.db,
          store,
          mode.config,
          await ctxFor(stranger.id),
          mediaId,
          { nowMs: IN_WINDOW_MS },
        );
        expect(refused.ok, `${stranger.who} reached an Eboard photo in ${mode.name} mode`).toBe(
          false,
        );
        // not_found rather than forbidden: confirming the object exists is itself a disclosure.
        if (!refused.ok) expect(refused.code, mode.name).toBe('not_found');
      }
    }

    // Still one, from the positive control. A refusal must never mint a URL for bytes the caller
    // may not have - a presigned URL needs no further authorization to fetch, so signing one and
    // then declining to return it would put the object one leaked log line from being public.
    expect(
      store.presignDownloads,
      'a refused caller still had a download URL signed for them',
    ).toHaveLength(1);
  });
});

