/**
 * Discrete notifications.
 *
 * **No `body` column and no `target` column, deliberately.** Both the display text and
 * the navigation destination are derived at READ time from `(type, params)`. A stored
 * route string left approvals permanently unresolved for eight migrations in v1
 * (engineering pitfall 8), and a stored English body is unlocalizable and correctable
 * only by rewriting history (roadmap debt 11). See ADR-0013.
 *
 * `params` is validated against a per-type Zod schema at write time, so a malformed
 * param fails the write rather than surfacing as broken text in an inbox months later.
 *
 * The other row kind in the inbox - a chat unread - is **not stored at all**. It is
 * derived from `channel.last_seq - cursor.last_read_seq`, because a stored count drifts
 * and a computed one cannot.
 */
export const notifications = pgTable(
  'notifications',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    recipientId: uuid('recipient_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    // Nullable: not every notification has a human actor (a deadline passing has none).
    actorId: uuid('actor_id').references(() => users.id, { onDelete: 'set null' }),
    // Nullable for dm-scoped notifications, since a DM belongs to no club. Every
    // audience query has to tolerate it.
    clubId: uuid('club_id').references(() => clubs.id, { onDelete: 'cascade' }),
    type: text('type').notNull(),
    params: jsonb('params').notNull(),
    // bigint, NOT bigserial. This references an outbox row's id; it is not a value
    // this table generates. bigserial would attach a sequence default, so an insert
    // that forgot to supply the id would silently get a sequence number and defeat
    // the idempotency index below rather than failing loudly.
    //
    // There is deliberately NO foreign key to outbox: the outbox is pruned nightly
    // after 7 days, and a cascade would delete a member's notification history along
    // with it. This column is an idempotency key, not a relationship.
    outboxEventId: bigint('outbox_event_id', { mode: 'number' }).notNull(),
    readAt: timestamp('read_at', { withTimezone: true }),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    // At-least-once safety. Outbox delivery WILL redeliver, and without this a
    // redelivered event fans out a second copy of every notification it produced.
    uniqueIndex('notifications_idempotency').on(t.outboxEventId, t.recipientId),
    // The inbox feed: newest first, per recipient.
    index('notifications_feed').on(t.recipientId, t.createdAt.desc()),
    // The badge counts unread rows only, so keep the index to those.
    index('notifications_unread')
      .on(t.recipientId)
      .where(sql`read_at is null`),
  ],
);

/**
 * Registered push targets.
 *
 * Push is targeted per DEVICE while suppression is per MEMBER via the read cursor. A
 * member with a laptop open and a phone in their pocket has not read the message, so
 * both devices are pushed and the phone rings; once they read it anywhere, the cursor
 * suppresses for that member everywhere at once. That is the behaviour you want, and it
 * is why this table exists separately from any notion of "is a socket alive".
 */
export const devices = pgTable(
  'devices',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    // Unique so re-registering the same physical device updates rather than duplicates,
    // which is what stops one phone receiving N copies of every push.
    pushToken: text('push_token').notNull().unique(),
    platform: text('platform').notNull(),
    lastSeenAt: timestamp('last_seen_at', { withTimezone: true }).notNull().defaultNow(),
    // Set when the provider reports the token dead. Kept rather than deleted so a
    // dedupe key referencing it stays resolvable.
    invalidatedAt: timestamp('invalidated_at', { withTimezone: true }),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    check('devices_platform_valid', sql`platform in ('ios', 'android', 'web')`),
    // The audience query walks a member's live devices.
    index('devices_live_for_user')
      .on(t.userId)
      .where(sql`invalidated_at is null`),
  ],
);

/**
 * Push dedupe ledger.
 *
 * At-least-once delivery means the worker will re-evaluate an event it has already
 * pushed. Without a record of what already went out, a redelivered event buzzes every
 * phone a second time - and unlike a duplicated database row, that one is impossible to
 * take back. Keyed exactly as SPEC/TECH/06 specifies.
 */
export const pushDeliveries = pgTable(
  'push_deliveries',
  {
    // bigint for the same reason as on notifications: a reference, not a generated
    // value, and no FK because outbox rows are pruned while this ledger must outlive
    // them - a pruned outbox row must never make an already-sent push re-sendable.
    outboxEventId: bigint('outbox_event_id', { mode: 'number' }).notNull(),
    deviceId: uuid('device_id')
      .notNull()
      .references(() => devices.id, { onDelete: 'cascade' }),
    sentAt: timestamp('sent_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [primaryKey({ columns: [t.outboxEventId, t.deviceId] })],
);

/**
 * Per-conversation mute.
 *
 * A muted conversation produces no push but its unread count still accrues - mute is
 * not "mark as read". Read by the push audience function and applying to EVERY scope,
 * not just dm: this is the "per-user mute and notification preferences" that had
 * nowhere to live before the audience function existed.
 */
export const channelMutes = pgTable(
  'channel_mutes',
  {
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    channelId: uuid('channel_id')
      .notNull()
      .references(() => channels.id, { onDelete: 'cascade' }),
    // NULL means muted indefinitely, rather than "not muted" - the row's existence is
    // the mute.
    mutedUntil: timestamp('muted_until', { withTimezone: true }),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [primaryKey({ columns: [t.userId, t.channelId] })],
);

/**
 * A conversation kept at the top of one person's chat list.
 *
 * **Personal, exactly like `race_pins`**, and the contrast with a *message* pin is worth being
 * precise about because the word does two jobs in this product. Pinning a message is an act of
 * authority in a shared room: an admin does it, everybody sees it, and `canPinInChannel` gates
 * it. Pinning a conversation is a fact about one person's own list - it needs no permission
 * beyond being able to read the channel, and nobody else can tell.
 *
 * Scope-agnostic on purpose: a club chat and a DM are pinned by the same row, so the list sorts
 * by one rule rather than by two that depend on what kind of row it is.
 *
 * The row's existence IS the pin, so unpinning is a delete and both directions are idempotent.
 */
export const channelPins = pgTable(
  'channel_pins',
  {
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    channelId: uuid('channel_id')
      .notNull()
      .references(() => channels.id, { onDelete: 'cascade' }),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [primaryKey({ columns: [t.userId, t.channelId] })],
);

/**
 * How far into a channel one person has cleared their own view.
 *
 * > **This is what "Delete chat" is, and what it deliberately is not.** Domain invariant 7 says a
 * > message is soft-deleted with a tombstone and never removed, and PRD/14 rule 3 says a thread
 * > goes read-only rather than being deleted. Both still hold: nothing here destroys a message or
 * > touches the other participant, who keeps the entire conversation and is never told. What it
 * > changes is one person's own floor into the log.
 *
 * `cleared_before_seq` is the highest seq the clearer has hidden, so every read of this channel
 * BY THIS USER filters `seq > cleared_before_seq`. Storing the watermark rather than deleting
 * rows is the only version that can be per-user at all - one log, two readers, two floors.
 *
 * Clearing advances `read_cursors.last_read_seq` in the same transaction. Without that a cleared
 * conversation would show zero messages and claim three unread, which is a contradiction the
 * reader cannot resolve or clear.
 */
export const channelClears = pgTable(
  'channel_clears',
  {
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    channelId: uuid('channel_id')
      .notNull()
      .references(() => channels.id, { onDelete: 'cascade' }),
    clearedBeforeSeq: integer('cleared_before_seq').notNull(),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    primaryKey({ columns: [t.userId, t.channelId] }),
    // A floor below zero is meaningless and a negative one would silently hide nothing, which
    // reads as "clear did not work" rather than as a bad write.
    check('channel_clears_seq_nonneg', sql`${t.clearedBeforeSeq} >= 0`),
  ],
);

/**
 * Reactions on a chat message.
 *
 * `PK (message_id, user_id, emoji)` is the whole behaviour: a member may add several
 * different emoji to one message, and cannot add the same one twice. "Reactions toggle on
 * and off" is then a delete-or-insert against that key rather than a read-then-write, so
 * two fast taps cannot leave a double row.
 *
 * > **No maintained count column, unlike `poll_options.vote_count`.** That column exists
 * > because vote *counts* are public while voter *identity* is gated, so the count cannot
 * > be derived from rows the viewer may not read. Reactions are visible to everyone, so
 * > the count is just `count(*)` over rows the viewer can already see, and a maintained
 * > copy would be a second source of truth for no gain.
 *
 * The emoji is a foreign key into `emoji_catalog`, which is what makes "a reaction is a real
 * emoji" a fact about the data rather than a rule a handler remembers. It replaced a check
 * constraint listing six emoji on 2026-08-13, when the set was opened to the whole catalog -
 * see ADR-0028. The property that mattered survives the change: the column renders directly
 * into every client and has never been allowed to hold arbitrary text.
 */
export const messageReactions = pgTable(
  'message_reactions',
  {
    messageId: uuid('message_id')
      .notNull()
      .references(() => messages.id, { onDelete: 'cascade' }),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    /*
      `restrict`, deliberately: an emoji leaving the catalog must not silently delete the
      reactions people made with it. A dataset upgrade that removes an emoji should fail loudly
      and be dealt with, rather than quietly erasing history.
    */
    emoji: text('emoji')
      .notNull()
      .references(() => emojiCatalog.emoji, { onDelete: 'restrict' }),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    primaryKey({ columns: [t.messageId, t.userId, t.emoji] }),
    // Reading a page of history loads every reaction for those messages at once, so the
    // access path is by message.
    index('message_reactions_by_message').on(t.messageId),
  ],
);

/**
 * Mentions.
 *
 * A mention notifies the mentioned member individually, and **only if they can actually
 * access that chat** - the audience function re-checks, because a client could name
 * anyone.
 */
export const messageMentions = pgTable(
  'message_mentions',
  {
    messageId: uuid('message_id')
      .notNull()
      .references(() => messages.id, { onDelete: 'cascade' }),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    /**
     * The name exactly as it was typed into the body, without the leading `@`.
     *
     * > **Stored rather than joined, which is the opposite of `senderName` and deliberately so.**
     * > A sender's name is re-joined on every read, so a rename updates everywhere at once. A
     * > mention cannot work that way: the characters `@Sean O Donnell` are sitting immutably in
     * > somebody else's message, and a client highlights the mention by finding that exact run of
     * > text. Join the current name instead and the day Sean renames, every mention of him in all
     * > of history silently stops being highlighted - the data is intact and the feature just
     * > quietly stops working, which is the worst way for it to fail.
     *
     * Nullable only for rows written before this column existed.
     */
    name: text('name'),
  },
  (t) => [primaryKey({ columns: [t.messageId, t.userId] })],
);

