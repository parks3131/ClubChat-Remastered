/**
 * `inviteToken`, not `inviteCode`. Nobody types it: it exists only inside a share
 * link. It is therefore 32 bytes of CSPRNG as base64url, matched exactly and
 * case-sensitively. Do NOT shorten it or make it case-insensitive - that shape
 * existed only to be typed by hand, and it is the shape that is feasible to
 * enumerate. See ADR-0010.
 */
export const clubs = pgTable('clubs', {
  id: uuid('id').primaryKey().defaultRandom(),
  name: text('name').notNull(),
  sport: text('sport').notNull(),
  description: text('description'),
  /**
   * The club's picture, as a media id.
   *
   * Identity media, exactly like a person's `image`: it goes to the public bucket and is fetched
   * through the same authorized hop. A club without one falls back to its initial, which is what
   * every avatar in the product does.
   */
  image: text('image'),
  joinPolicy: text('join_policy').notNull().default('open'),
  /**
   * The ADMIN link. Redeeming it joins instantly, whatever the join policy says.
   *
   * An admin sharing the link has already made the decision the `request` policy exists to
   * capture, so the link stays the private side channel it has always been.
   */
  inviteToken: text('invite_token').notNull().unique(),
  /**
   * The MEMBER link. Same club, and it obeys the join policy instead of bypassing it.
   *
   * > **Two tokens rather than one token plus a marker of who shared it** (ADR-0025). A link is a
   * > bearer string that gets pasted, forwarded and screenshotted, so anything qualifying it -
   * > a query parameter, a signature - is something that can be stripped or lost in a paste. Two
   * > opaque tokens cannot be confused for each other and there is nothing to strip: the effect
   * > IS the string. Guessing the other one is guessing 32 bytes of CSPRNG.
   *
   * On an `open` club the two behave identically, because there is nothing to bypass.
   */
  memberInviteToken: text('member_invite_token').notNull().unique(),
  inviteTokenRotatedAt: timestamp('invite_token_rotated_at', { withTimezone: true }),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
});

export const clubMemberships = pgTable(
  'club_memberships',
  {
    clubId: uuid('club_id')
      .notNull()
      .references(() => clubs.id, { onDelete: 'cascade' }),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    role: text('role').notNull(),
    joinedAt: timestamp('joined_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    primaryKey({ columns: [t.clubId, t.userId] }),
    // Domain invariant 1: exactly one Owner per club, always. Enforced here rather
    // than in a handler because an ownerless club has NO recovery path, and because
    // the ownership-transfer path must demote before it promotes - the constraint is
    // checked per statement, so the other order momentarily holds two owners and
    // correctly fails.
    uniqueIndex('club_memberships_one_owner')
      .on(t.clubId)
      .where(sql`role = 'owner'`),
    check('club_memberships_role_valid', sql`role in ('owner', 'admin', 'member')`),
    index('club_memberships_by_user').on(t.userId),
  ],
);

/**
 * Who may never come back.
 *
 * > **Removing somebody from an open club did not remove them.** `joinClub` admitted straight into
 * > a club whose policy is `open` with no check against a prior removal, so an ejected member
 * > tapped Join and returned. And since ADR-0010 made the share link the only invite mechanism, a
 * > link already in their possession kept working, with token rotation - which invalidates every
 * > outstanding link for everybody - as the sole remedy for excluding one person.
 *
 * A separate row from `club_memberships` rather than a flag on it, because the two facts are
 * different and a banned person is usually not a member at all: membership says "in this club now",
 * a ban says "may not be". Folding them together would also bar a member who left of their own
 * accord, and leaving is a normal, blameless act.
 *
 * `banned_by` is `SET NULL` rather than cascade, deliberately. The attribution is the safeguard
 * (ADR-0021), so the ban must outlive the account that imposed it - losing the row because an admin
 * later deleted their account would quietly unban somebody.
 */
export const clubBans = pgTable(
  'club_bans',
  {
    clubId: uuid('club_id')
      .notNull()
      .references(() => clubs.id, { onDelete: 'cascade' }),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    /** Null only where the banning admin's account has since been deleted. */
    bannedBy: uuid('banned_by').references(() => users.id, { onDelete: 'set null' }),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    // One ban per person per club. Banning twice is idempotent rather than an error, which
    // matters because two admins can reach for it at the same moment.
    primaryKey({ columns: [t.clubId, t.userId] }),
    index('club_bans_by_user').on(t.userId),
  ],
);

/**
 * Pending and decided join requests.
 *
 * The partial unique index is what makes decisions idempotent: two admins hitting Approve
 * on the same request must produce **one** membership, one notification and one recorded
 * decider. Scoped to `pending` so a denied request can be re-filed later - a plain
 * UNIQUE would permanently bar anyone who was ever turned down.
 */
export const clubJoinRequests = pgTable(
  'club_join_requests',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    clubId: uuid('club_id')
      .notNull()
      .references(() => clubs.id, { onDelete: 'cascade' }),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    status: text('status').notNull().default('pending'),
    decidedBy: uuid('decided_by').references(() => users.id, { onDelete: 'set null' }),
    decidedAt: timestamp('decided_at', { withTimezone: true }),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    uniqueIndex('club_join_requests_one_pending')
      .on(t.clubId, t.userId)
      .where(sql`status = 'pending'`),
    check('club_join_requests_status_valid', sql`status in ('pending', 'approved', 'denied')`),
    index('club_join_requests_by_club').on(t.clubId, t.status),
  ],
);

