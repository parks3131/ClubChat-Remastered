/**
 * One entry on the club's week. The feature that replaces the screenshotted Excel sheet.
 *
 * **Answers three questions and only these three:** where (`location`), when (`meetupDate`
 * plus `meetupTime`) and what (`description`, free text). The first two are `NOT NULL` -
 * the surface exists to answer them, and a club that has not decided yet types "TBC", which
 * tells a member something a blank does not.
 *
 * **There is no type, category or kind column, and that absence is the design.** A per-club,
 * admin-editable catalog of activity types was specified in full and rejected; see ADR-0029,
 * which records it at length precisely so a reader who finds this table and assumes the
 * missing column is an oversight does not add one back.
 *
 * **`meetupDate` is a DATE and `meetupTime` is a TIME, deliberately not one timestamp.** A
 * club's week is local wall-clock and no club carries a timezone, so there is nothing to
 * convert from - and an instant would put Tuesday's meetup on Monday for a member reading
 * from another country. The week groups by `meetupDate`, and that grouping must not depend on
 * who is looking.
 *
 * No unique key on (clubId, meetupDate): a day holds as many meetups as the club needs, in
 * time order. A morning session and an evening social are two rows, not one squashed together.
 */
export const meetups = pgTable(
  'meetups',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    clubId: uuid('club_id')
      .notNull()
      .references(() => clubs.id, { onDelete: 'cascade' }),
    meetupDate: date('meetup_date').notNull(),
    meetupTime: time('meetup_time').notNull(),
    location: text('location').notNull(),
    description: text('description'),
    createdBy: uuid('created_by').references(() => users.id, { onDelete: 'set null' }),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [index('meetups_by_club').on(t.clubId, t.meetupDate, t.meetupTime)],
);

/**
 * A nudge: an admin pushing one meetup at the whole club.
 *
 * **This row exists to be a rate limit, not to be read.** Weekly Meetups notifies nobody
 * (PRD/08 rule 11) and Nudge is the single deliberate exception to that, so the only thing
 * standing between it and being the reason members turn push off is the cooldown - and the
 * cooldown is an `EXCLUDE` constraint, not a check in a handler, because two admins tapping the
 * bell at the same moment is exactly the case a read-then-write loses. See ADR-0030.
 *
 * **At most one nudge per MEETUP per hour** since 2026-08-14 (ADR-0031, superseding ADR-0030's
 * per-club rule). Four meetups in a day are four things to tell people about and carry four
 * independent clocks; nudging the morning run no longer silences the evening social.
 *
 * **Drizzle cannot express an exclusion constraint**, so it is raw SQL in the migration and
 * this declaration does not describe it. Do not conclude from this file that the table has no
 * constraints.
 *
 * `meetupId` clears rather than cascades, and is nullable for that reason - which now also
 * decides the constraint's behaviour: **a NULL operand takes a row out of an exclusion
 * constraint**, so a nudge whose meetup has been deleted blocks nothing. That is right under
 * the per-meetup rule, where there is no longer a meetup to nudge, and was exactly wrong under
 * the per-club one.
 */
export const meetupNudges = pgTable(
  'meetup_nudges',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    clubId: uuid('club_id')
      .notNull()
      .references(() => clubs.id, { onDelete: 'cascade' }),
    meetupId: uuid('meetup_id').references(() => meetups.id, { onDelete: 'set null' }),
    actorId: uuid('actor_id').references(() => users.id, { onDelete: 'set null' }),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
    /**
     * When the bell comes back, stored rather than computed.
     *
     * **The window is a column because `timestamptz + interval` is STABLE, not IMMUTABLE** - it
     * depends on the session's time zone - so it cannot appear in an index expression, and an
     * exclusion constraint is an index. Writing the end of the window down turns the constraint
     * into `tstzrange(created_at, cooldown_until)` over two plain columns, which is immutable.
     *
     * It also makes the hour data rather than schema: shortening the cooldown becomes a new
     * default and a handler change, not a constraint rewrite.
     */
    cooldownUntil: timestamp('cooldown_until', { withTimezone: true })
      .notNull()
      .default(sql`now() + interval '1 hour'`),
  },
  (t) => [index('meetup_nudges_by_meetup').on(t.meetupId, t.cooldownUntil)],
);

