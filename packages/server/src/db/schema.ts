/**
 * Requests to rejoin the Eboard space.
 *
 * > **The path that in normal operation nobody uses**, and the reason it still has to exist.
 * > Promotion to admin auto-joins and demotion auto-removes, so membership tracks the admin
 * > tier by itself. What it cannot handle is an admin who **deliberately left** the space and
 * > later wants back in: they are still admin-tier, so no promotion will re-add them, and
 * > PRD/10 rule 5 says only existing members may add anybody - which they are not.
 * >
 * > Without this table that person has no route back in at all except another member noticing.
 *
 * Added in Phase 3.75a. It was specified in TECH/09 and depended on by PRD/10 from the start,
 * was the only one of v1's 29 tables with no remaster counterpart, and had simply never been
 * built - a domain gap rather than a delivery one.
 *
 * Deliberately shaped exactly like `race_join_requests` and `club_join_requests`, down to the
 * partial unique index: three tables answering the same question should not answer it in three
 * shapes. `decided_by` is `set null` for the same reason theirs are - a decision outlives the
 * account that made it.
 */
export const eboardJoinRequests = pgTable(
  'eboard_join_requests',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    eboardId: uuid('eboard_id')
      .notNull()
      .references(() => eboardChannels.id, { onDelete: 'cascade' }),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    status: text('status').notNull().default('pending'),
    decidedBy: uuid('decided_by').references(() => users.id, { onDelete: 'set null' }),
    decidedAt: timestamp('decided_at', { withTimezone: true }),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    // Scoped to pending, so a denied request can be re-filed. A plain UNIQUE would
    // permanently bar anyone who was ever turned down.
    uniqueIndex('eboard_join_requests_one_pending')
      .on(t.eboardId, t.userId)
      .where(sql`status = 'pending'`),
    check('eboard_join_requests_status_valid', sql`status in ('pending', 'approved', 'denied')`),
    index('eboard_join_requests_by_eboard').on(t.eboardId, t.status),
  ],
);

// ---------------------------------------------------------------------------
// The channel abstraction - one concept, four scopes
// ---------------------------------------------------------------------------

/**
 * Channels.
 *
 * `lastSeq` is the per-channel message counter. It is bumped inside the same
 * transaction that inserts the message, under a row lock held until commit, which
 * is what makes `seq` gapless. See appendMessage and SPEC/TECH/02-channel-log.md.
 *
 * `clubId` is nullable ONLY for the dm scope: two people who share two clubs must
 * get one thread, not two, so a DM cannot belong to a club. The check constraint
 * stops the other three scopes from ever exploiting the relaxed column.
 */
export const channels = pgTable(
  'channels',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    clubId: uuid('club_id').references(() => clubs.id, { onDelete: 'cascade' }),
    scope: text('scope').notNull(),
    // For scope='club' this is the club id, for 'eboard' the eboard id, and so on.
    // NOT NULL on purpose: a nullable column inside a unique index is treated as
    // distinct by Postgres and would silently defeat the constraint below.
    scopeId: uuid('scope_id').notNull(),
    lastSeq: integer('last_seq').notNull().default(0),
    /**
     * The per-channel REVISION counter, which is not the message counter.
     *
     * `lastSeq` answers "how many messages are there" and must stay gapless, so it is bumped
     * only by an append. `lastRev` answers a different question - **"what has changed"** - and is
     * bumped by an append AND by every later mutation of a message: a pin, a soft delete, a
     * reaction.
     *
     * > **Two counters rather than one, because reusing `seq` would reorder the log.** Bumping a
     * > message's `seq` when somebody pins it would move it to the end of the conversation and
     * > punch a hole where it used to be, which is exactly the phantom gap the gapless design
     * > exists to make unrepresentable.
     *
     * A monotonic integer rather than a timestamp, for the reason `seq` is one: a client asking
     * "what have I not seen" gets an integer comparison with no clock in it, and no two rows
     * committing out of order can slip past the mark.
     */
    lastRev: integer('last_rev').notNull().default(0),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    check('channels_scope_valid', sql`scope in ('club', 'race', 'eboard', 'dm')`),
    // Domain invariant 2: exactly one main channel per club. Any lookup for "the
    // club's main channel" must also exclude race- and eboard-scoped channels;
    // forgetting that predicate produced "more than one row returned by a subquery"
    // twice in v1.
    uniqueIndex('channels_one_main_per_club')
      .on(t.clubId)
      .where(sql`scope = 'club'`),
    uniqueIndex('channels_scope_identity').on(t.scope, t.scopeId),
    check('channels_dm_has_no_club', sql`(club_id is null) = (scope = 'dm')`),
  ],
);

/**
 * The channel log. One row per message, ever - no per-recipient copy (ADR-0003).
 *
 * Both `senderId` and `clientMsgId` are NOT NULL, and that is load-bearing rather
 * than tidiness: Postgres treats NULLs as distinct inside a unique index, so one
 * nullable column silently defeats the idempotency constraint below. System
 * messages therefore use the reserved system-actor UUID, never NULL - and system
 * messages are exactly the class the worker retries after a crash, so they are
 * exactly the class that must not slip through.
 */
export const messages = pgTable(
  'messages',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    channelId: uuid('channel_id')
      .notNull()
      .references(() => channels.id, { onDelete: 'cascade' }),
    seq: integer('seq').notNull(),
    senderId: uuid('sender_id')
      .notNull()
      .references(() => users.id, { onDelete: 'restrict' }),
    type: text('type').notNull().default('text'),
    body: text('body'),
    clientMsgId: uuid('client_msg_id').notNull(),
    /**
     * What this message is a card FOR.
     *
     * Exactly one is set on a card message and all three are null on an ordinary one. They
     * exist so that **deleting the underlying object removes its card** rather than leaving
     * a dead link in the conversation - without them the effect has no way to find the
     * message it posted. No foreign key: the card outlives nothing, but the object may be
     * deleted before the effect runs, and an FK would either block the delete or cascade the
     * message away without a tombstone.
     */
    linkedPollId: uuid('linked_poll_id'),
    linkedEventId: uuid('linked_event_id'),
    linkedMeetingId: uuid('linked_meeting_id'),
    /**
     * What this message is a reply to: the quoted message's `seq`, in this same channel.
     *
     * A seq rather than a message id, and that is what makes the reference safe as well as
     * cheap. `(channel_id, seq)` is this table's other unique key, so the foreign key below
     * can be composite - which means a reply **cannot** point outside its own channel. An id
     * reference could, and the read that draws the quote would then have to re-check the
     * channel itself, which is a predicate restated in a second place (failure mode 9).
     *
     * The quote's CONTENTS are not stored here. They are joined from the referenced row on
     * every read, so a deleted original stops showing its text everywhere at once - see
     * `MessageReplyRef` in the shared package.
     */
    replyToSeq: integer('reply_to_seq'),
    /**
     * The attached object, for a photo or document message.
     *
     * No foreign key, deliberately: `media_objects.owner_id` points back at the message, and a
     * mutual FK would make either insert impossible without deferred constraints. The message
     * is the owner; this is the reference.
     */
    mediaId: uuid('media_id'),
    /** Shown on a document bubble. A photo carries neither. */
    documentName: text('document_name'),
    documentSize: integer('document_size'),
    pinned: boolean('pinned').notNull().default(false),
    /**
     * When it was pinned, or null.
     *
     * > **A boolean cannot order a pinned strip and cannot date one.** Without this the strip
     * > could only sort by `seq` - the age of the MESSAGE - so re-pinning something old put it
     * > back in its old place rather than at the front, and a strip capped at four dropped it
     * > again immediately. The notice also had no date of its own to show, only the message's.
     *
     * Set on every pin, including a re-pin, so pinning something again genuinely makes it the
     * most recent. Cleared on unpin, so the column never claims a pin that is not there.
     */
    pinnedAt: timestamp('pinned_at', { withTimezone: true }),
    // Soft delete with a tombstone, never a removal: a message vanishing
    // mid-conversation makes the replies unreadable (domain invariant 7).
    deletedAt: timestamp('deleted_at', { withTimezone: true }),
    /**
     * When the sender last corrected this message. Null for the great majority.
     *
     * > **Set is what makes the bubble say "Edited".** An edit that changed the text and left no
     * > trace would let a message become something other than what was replied to or reacted to,
     * > with nothing on screen admitting it - `PRD/05` rule 9a.
     *
     * The old text is deliberately not kept anywhere. There is no `message_revisions` table and
     * no `previous_body` column, because a five-minute correction window is for fixing a typo,
     * and a stored history would turn every one of them into a permanent record of what somebody
     * meant to unsay. See ADR-0033.
     *
     * Nullable with no default, so every row that predates edits reads "never edited" rather
     * than "edited at the moment of the migration".
     */
    editedAt: timestamp('edited_at', { withTimezone: true }),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
    /**
     * The channel revision at which this row last changed. See `channels.lastRev`.
     *
     * > **This is what makes a deletion reach a device that was offline when it happened.** Sync
     * > used to ask for `seq > mine`, so a row the client already held was never fetched again -
     * > and a pin, a tombstone and a reaction all mutate rows BELOW that mark. A client that was
     * > disconnected when a message was deleted kept showing that message, with its text,
     * > indefinitely. `PRD/17` item 14, and it is a moderation hole rather than staleness.
     *
     * Every message has one from insert, so a single watermark answers both halves of sync: a new
     * message and a changed message are the same question asked of `rev`.
     */
    rev: integer('rev').notNull().default(0),
  },
  (t) => [
    uniqueIndex('messages_channel_seq').on(t.channelId, t.seq),
    // The sync index. Sync walks `rev` ascending within a channel, so this is to reconciliation
    // what `messages_channel_seq_desc` is to history paging.
    index('messages_channel_rev').on(t.channelId, t.rev),
    // Idempotency. A retry after a flaky network hits this index and the handler
    // returns the existing row's seq instead of erroring, which is what makes the
    // client's send outbox safe to retry aggressively.
    uniqueIndex('messages_idempotency').on(t.channelId, t.senderId, t.clientMsgId),
    // The paging index: history reads walk backward from the live tail.
    index('messages_channel_seq_desc').on(t.channelId, t.seq.desc()),
    // Highlights must not lose pins past the loaded window, so the pinned and
    // announcement lists are server-side queries over the WHOLE channel rather
    // than a computed slice of loaded history.
    index('messages_pinned')
      .on(t.channelId, t.seq)
      .where(sql`pinned`),
    index('messages_announcements')
      .on(t.channelId, t.seq)
      .where(sql`type = 'announcement'`),
    check('messages_seq_positive', sql`seq > 0`),
    // Partial, because only card messages carry these - the index stays proportional to
    // the number of cards rather than to the whole log.
    index('messages_linked_poll')
      .on(t.linkedPollId)
      .where(sql`linked_poll_id is not null`),
    index('messages_linked_event')
      .on(t.linkedEventId)
      .where(sql`linked_event_id is not null`),
    index('messages_linked_meeting')
      .on(t.linkedMeetingId)
      .where(sql`linked_meeting_id is not null`),
    // The Gallery index. Partial, so it stays proportional to photos rather than to the
    // whole log - and server-side, so the gallery cannot silently lose photos past a
    // loaded window the way v1's client-side slice did.
    index('messages_with_media')
      .on(t.channelId, t.seq.desc())
      .where(sql`media_id is not null and deleted_at is null`),
    // A card is a card for exactly one thing, or for nothing at all.
    check(
      'messages_at_most_one_link',
      sql`(CASE WHEN linked_poll_id IS NOT NULL THEN 1 ELSE 0 END
         + CASE WHEN linked_event_id IS NOT NULL THEN 1 ELSE 0 END
         + CASE WHEN linked_meeting_id IS NOT NULL THEN 1 ELSE 0 END) <= 1`,
    ),
    /*
     * A reply points at a real message in the SAME channel, enforced by the data rather than
     * by the handler that writes it.
     *
     * Composite and self-referencing, against the `(channel_id, seq)` unique key. That shape is
     * the whole point: `channel_id` appears on both sides, so "the quoted message is in this
     * channel" is not a check anybody can forget to write. Cascading on delete because a
     * message row is only ever hard-deleted by its channel going, which takes the replies too.
     */
    foreignKey({
      columns: [t.channelId, t.replyToSeq],
      foreignColumns: [t.channelId, t.seq],
      name: 'messages_reply_to_fk',
    }).onDelete('cascade'),
    /*
     * You can only reply to something already said.
     *
     * Strictly less-than rather than not-equal, which also rules out a message replying to
     * itself: a self-referencing foreign key is satisfied by the row being inserted, so
     * `reply_to_seq = seq` would otherwise be accepted and would render as a bubble quoting
     * itself forever.
     */
    check('messages_reply_precedes', sql`reply_to_seq is null or reply_to_seq < seq`),
    /*
     * Partial, for the same reason as the card links above: it stays proportional to the
     * number of replies rather than to the whole log. It exists for the cascade - without an
     * index on the referencing side, deleting a channel scans this table once per message it
     * holds, which is quadratic in the size of the channel being deleted.
     */
    index('messages_reply_to')
      .on(t.channelId, t.replyToSeq)
      .where(sql`reply_to_seq is not null`),
  ],
);

/**
 * Read cursors.
 *
 * Opening a chat sets `lastReadSeq = channel.lastSeq`. That is the only thing that
 * clears an unread count. The count itself is never stored: it is
 * `channel.lastSeq - cursor.lastReadSeq`, which is O(1) and cannot drift.
 *
 * This table is also what suppresses push, and that is a correctness requirement
 * rather than an optimisation - `lastReadSeq >= N` is a fact committed to Postgres
 * that the member saw the message, whereas a live socket is proof of nothing
 * (ADR-0008).
 */
export const readCursors = pgTable(
  'read_cursors',
  {
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    channelId: uuid('channel_id')
      .notNull()
      .references(() => channels.id, { onDelete: 'cascade' }),
    lastReadSeq: integer('last_read_seq').notNull().default(0),
    updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [primaryKey({ columns: [t.userId, t.channelId] })],
);

// ---------------------------------------------------------------------------
// The transactional outbox
// ---------------------------------------------------------------------------

/**
 * Every command handler writes domain rows AND outbox events in one transaction.
 * Either both land or neither does - a guarantee an external queue cannot give you,
 * and the entire reason the outbox exists rather than publishing from a handler.
 *
 * `processedAt`, not `publishedAt`, and the distinction is deliberate. ADR-0006
 * defines `published_at` as meaning "handed to Kafka, NOT effect performed".
 * Phase 0 has no Kafka - the worker drains this table directly with
 * FOR UPDATE SKIP LOCKED - so here the column genuinely does mean "effect
 * performed". Using the Kafka-era name for a non-Kafka meaning is precisely the
 * drift that ADR warns about. Phase 1.5 renames this column when the relay and
 * Kafka arrive, which is one migration and is already budgeted in that ADR.
 *
 * `partitionKey` is the ordering domain (a channel id or a club id). It exists now,
 * before Kafka does, because it is the key Kafka must eventually partition by:
 * ordering is guaranteed within a partition only, and any other key silently breaks
 * per-channel ordering with "a system message arriving before the event that caused
 * it" as the symptom.
 */
export const outbox = pgTable(
  'outbox',
  {
    id: bigserial('id', { mode: 'number' }).primaryKey(),
    partitionKey: text('partition_key').notNull(),
    eventType: text('event_type').notNull(),
    payload: jsonb('payload').notNull(),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
    processedAt: timestamp('processed_at', { withTimezone: true }),
    attempts: integer('attempts').notNull().default(0),
    /**
     * When this row may be claimed again. `now()` for a row that has never failed.
     *
     * Without this the drain re-claims a failing row on every 250ms tick, so the whole
     * attempt budget is spent in about a second and any outage longer than that parks the
     * row permanently. The delay is what makes the retries mean anything.
     */
    nextAttemptAt: timestamp('next_attempt_at', { withTimezone: true }).notNull().defaultNow(),
    lastError: text('last_error'),
  },
  (t) => [
    // The relay claim index. Partial on unprocessed rows so the index stays small
    // no matter how much history accumulates.
    index('outbox_unprocessed')
      .on(t.partitionKey, t.id)
      .where(sql`processed_at is null`),
  ],
);

