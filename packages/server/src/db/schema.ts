/**
 * Every emoji that may be reacted with.
 *
 * **Static reference data we do not author**, seeded by migration from a pinned
 * `emojibase-data` release and regenerated by `scripts/generate-emoji-catalog.mjs`. It is here
 * rather than in a constant so that a **foreign key can be the validator**: "the emoji is a real
 * emoji" is an invariant, and this repo's rule is that an invariant belongs in a constraint
 * because a handler races and a constraint does not. See ADR-0028.
 *
 * It also settles normalisation. `❤️` and `❤` are different strings and the same emoji to a
 * reader; the catalog holds exactly one of them, so the other is refused at the boundary instead
 * of becoming a second pill with a count of one. That is why the quick-reaction row in the shared
 * package is generated from this data rather than typed out - the old hand-written `👍` was
 * U+1F44D where the dataset says U+1F44D U+FE0F.
 *
 * Skin tone variants are deliberately absent: 330 emoji support them and including them would
 * make this 3,564 rows. The table can gain them later without a contract change.
 */
export const emojiCatalog = pgTable('emoji_catalog', {
  /** The canonical encoding, and the primary key every reaction points at. */
  emoji: text('emoji').primaryKey(),
  /** "face with tears of joy". The picker's accessible name. */
  label: text('label').notNull(),
  /** The dataset's group key: `smileys-emotion`, `flags`, and so on. */
  group: text('group').notNull(),
  /**
   * Position in the dataset's own order.
   *
   * Two jobs: the picker lists in it, and the pill row breaks ties with it - so two emoji on
   * equal counts hold their positions rather than swapping about. PRD/05 rule R3.
   */
  ordinal: integer('ordinal').notNull(),
});

