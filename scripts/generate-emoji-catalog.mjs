/**
 * Generate the emoji catalog from `emojibase-data`.
 *
 * **One source, two consumers.** The dataset is a pinned npm release; this script turns it into
 * exactly two artifacts, and nothing else in the repo may hand-maintain a list of emoji:
 *
 *  - `packages/shared/src/emoji-catalog.generated.ts` - what the client's picker searches and what
 *    the server validates against, so the two can never disagree about what exists.
 *  - `packages/server/src/db/emoji-catalog.seed.sql` - the rows for `emoji_catalog`, so the
 *    foreign key can be the validator. See ADR-0028.
 *
 * Re-run it when the pinned version changes, in the same change, or the generated files silently
 * describe a different release than `package.json` claims - the same hazard `render-diagrams.sh`
 * carries and the same rule.
 *
 *   node scripts/generate-emoji-catalog.mjs
 *
 * **Components are excluded.** 26 of the dataset's entries are not emoji anybody reacts with -
 * regional indicator letters, skin tone modifiers - and they are the pieces other emoji are built
 * from rather than things in their own right. The dataset marks them by having no `group`.
 *
 * **Skin tone variants are excluded**, per ADR-0028: the base emoji is taken and its `skins` are
 * dropped. That is a product decision rather than a data one, and it is the line to move if tones
 * are ever offered.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const compact = require('emojibase-data/en/compact.json');
const messages = require('emojibase-data/en/messages.json');
const version = JSON.parse(
  readFileSync(join(root, 'packages/shared/package.json'), 'utf8'),
).dependencies['emojibase-data'];

/** Group key by numeric id, so the generated data carries a name rather than an index. */
const groupName = new Map(messages.groups.map((g) => [Number(g.order), g.key]));

const rows = compact
  // No `group` means a component: a regional indicator, a tone modifier, a joiner piece.
  .filter((e) => e.group !== undefined && groupName.get(e.group) !== 'component')
  .map((e) => ({
    emoji: e.unicode,
    label: e.label,
    group: groupName.get(e.group) ?? 'symbols',
    // The dataset's own ordering, which is the Unicode order people expect a picker to be in -
    // and what breaks ties in the pill row so equal counts cannot shuffle. See PRD/05 rule R3.
    order: e.order ?? 0,
    tags: e.tags ?? [],
  }))
  .sort((a, b) => a.order - b.order)
  .map((e, index) => ({ ...e, order: index }));

if (rows.length < 1000) throw new Error(`only ${rows.length} emoji - the dataset shape changed`);

/*
 * The six quick reactions, resolved AGAINST the catalog rather than written out.
 *
 * > **This is not tidiness.** The old constant held `👍` as U+1F44D and the dataset holds it as
 * > U+1F44D U+FE0F. Hand-writing the quick row again would mean the one emoji people reach for
 * > most is the one the foreign key refuses.
 */
const QUICK = ['thumbs up', 'red heart', 'face with tears of joy', 'fire', 'party popper', 'face with open mouth'];
const quick = QUICK.map((label) => {
  const hit = rows.find((r) => r.label === label);
  if (!hit) throw new Error(`quick reaction "${label}" is not in the catalog`);
  return hit.emoji;
});

const banner = `/**
 * GENERATED by scripts/generate-emoji-catalog.mjs from emojibase-data@${version}. Do not edit.
 *
 * See ADR-0028. Re-run the generator in the same change as any version bump.
 */`;

writeFileSync(
  join(root, 'packages/shared/src/emoji-catalog.generated.ts'),
  `${banner}

export type CatalogEmoji = {
  /** The canonical encoding. Anything else is refused by the foreign key. */
  emoji: string;
  label: string;
  group: string;
  /** Position in the dataset's own order. Breaks ties in the pill row - PRD/05 rule R3. */
  order: number;
  /** Search keys. "lol" finds the crying-laughing face because the dataset says so. */
  tags: readonly string[];
};

export const emojiCatalogVersion = ${JSON.stringify(version)};

/** The six offered without opening the picker, resolved from the catalog - never hand-written. */
export const quickReactions = ${JSON.stringify(quick)} as const;

export const emojiCatalog: readonly CatalogEmoji[] = ${JSON.stringify(rows)};
`,
);

const sql = rows
  .map(
    (r) =>
      `  (${lit(r.emoji)}, ${lit(r.label)}, ${lit(r.group)}, ${r.order})`,
  )
  .join(',\n');

writeFileSync(
  join(root, 'packages/server/src/db/emoji-catalog.seed.sql'),
  `-- GENERATED by scripts/generate-emoji-catalog.mjs from emojibase-data@${version}. Do not edit.
--
-- Seeds emoji_catalog. Idempotent, so re-running a migration or seeding a fresh database
-- twice is harmless. See ADR-0028.
INSERT INTO emoji_catalog (emoji, label, "group", ordinal) VALUES
${sql}
ON CONFLICT (emoji) DO UPDATE
  SET label = EXCLUDED.label, "group" = EXCLUDED."group", ordinal = EXCLUDED.ordinal;
`,
);

/** Single-quote a SQL string literal, doubling any quote inside it. */
function lit(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

console.log(
  `emoji catalog: ${rows.length} emoji from emojibase-data@${version}, quick row ${quick.join(' ')}`,
);
